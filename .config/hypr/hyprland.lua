-- Hyprland configuration (Lua) — https://wiki.hypr.land/Configuring/Start/

hl.config({ autogenerated = false })

hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd --all")
	hl.exec_cmd("systemctl --user start hyprland-session.target")
	hl.exec_cmd("$HOME/.local/bin/papirus-grey-folders")
end)

hl.env("QT_QPA_PLATFORMTHEME", "qt6ct") -- Qt platform theme (qt6ct-kde + Noctalia KColorScheme)
hl.env("_JAVA_AWT_WM_NONREPARENTING", "1") -- Java/Swing windows render blank without it
-- GTK creates ext_background_effect objects but never sets a blur region, which
-- suppresses Hyprland's own blur. Disable it so the compositor blurs GTK windows.
hl.env("GDK_WAYLAND_DISABLE", "ext_background_effect_manager_v1")

hl.config({
	input = {
		kb_layout = "de,tr",
		kb_options = "grp:alt_shift_toggle",
		repeat_delay = 250,
		numlock_by_default = true,
		follow_mouse = 1,
		touchpad = {
			tap_to_click = true,
			natural_scroll = true,
		},
	},
	general = {
		layout = "dwindle",
	},
	decoration = {
		active_opacity = 1.0,
		inactive_opacity = 1.0,
		shadow = {
			enabled = true,
			range = 30,
			render_power = 4,
			offset = "0 5",
			color = "rgba(00000070)",
		},
	},
	misc = {
		disable_hyprland_logo = true,
		disable_splash_rendering = true,
	},
	-- Automatic HDR switching for fullscreen HDR content re-modesets DP-1, blanking the screen
	-- each time a video goes fullscreen (confirmed 2026-10-29); the HDR400 panel gains little.
	render = {
		cm_auto_hdr = 0,
	},
	dwindle = {
		preserve_split = true,
	},
	master = {
		mfact = 0.5,
	},
})

-- Material 3 motion: entrances decelerate and settle, exits accelerate away in half the time,
-- everything else uses the standard curve. Speed is in units of 100 ms.
hl.curve("emphasizedDecel", { type = "bezier", points = { {0.05, 0.7}, {0.1, 1} } })
hl.curve("emphasizedAccel", { type = "bezier", points = { {0.3, 0}, {0.8, 0.15} } })
hl.curve("standard", { type = "bezier", points = { {0.2, 0}, {0, 1} } })

hl.animation({ leaf = "windowsIn", enabled = true, speed = 4, bezier = "emphasizedDecel", style = "popin 90%" })
hl.animation({ leaf = "windowsOut", enabled = true, speed = 2, bezier = "emphasizedAccel", style = "popin 90%" })
hl.animation({ leaf = "windowsMove", enabled = true, speed = 3, bezier = "standard" })
hl.animation({ leaf = "workspaces", enabled = true, speed = 3.5, bezier = "standard", style = "slide" })
hl.animation({ leaf = "specialWorkspace", enabled = true, speed = 3.5, bezier = "emphasizedDecel", style = "slidevert" })
hl.animation({ leaf = "fade", enabled = true, speed = 3, bezier = "standard" })
hl.animation({ leaf = "fadeOut", enabled = true, speed = 2, bezier = "emphasizedAccel" })
hl.animation({ leaf = "border", enabled = true, speed = 3, bezier = "standard" })

